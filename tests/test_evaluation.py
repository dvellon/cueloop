from __future__ import annotations

from array import array
import hashlib
import json
from pathlib import Path
import tempfile
import unittest
import wave

from cueloop.evaluation import (
    DatasetValidationError,
    audio_windows,
    evaluate,
    load_evaluation_manifest,
)
from cueloop.model import Classification


class AmplitudeClassifier:
    def classify(self, samples: tuple[int, ...], sample_rate: int) -> Classification:
        detected = max(abs(value) for value in samples) > 100
        return Classification(
            scores={
                "door_knock": 0.9 if detected else 0.01,
                "alarm_beep": 0.01,
                "dog_bark": 0.01,
                "attention_call": 0.01,
                "background": 0.01 if detected else 0.98,
                "unknown": 0.01,
            },
            inference_ms=2.5,
            model_name="test-amplitude",
            evidence_tier="simulated",
        )


def write_wav(path: Path, value: int) -> str:
    payload = array("h", [value] * 32_000).tobytes()
    with wave.open(str(path), "wb") as output:
        output.setnchannels(1)
        output.setsampwidth(2)
        output.setframerate(16_000)
        output.writeframes(payload)
    return hashlib.sha256(path.read_bytes()).hexdigest()


class EvaluationTests(unittest.TestCase):
    def make_manifest(self, directory: Path, *, consent: bool = True) -> Path:
        positive = directory / "positive.wav"
        negative = directory / "negative.wav"
        positive_sha = write_wav(positive, 1000)
        negative_sha = write_wav(negative, 0)
        manifest = {
            "schema_version": 1,
            "dataset_id": "owned-test-fixtures",
            "records": [
                {
                    "id": "positive",
                    "path": positive.name,
                    "labels": ["door_knock"],
                    "split": "test",
                    "source": "generated by unit test",
                    "license": "project-owned synthetic fixture",
                    "consent_confirmed": consent,
                    "sha256": positive_sha,
                },
                {
                    "id": "negative",
                    "path": negative.name,
                    "labels": [],
                    "split": "test",
                    "source": "generated by unit test",
                    "license": "project-owned synthetic fixture",
                    "consent_confirmed": True,
                    "sha256": negative_sha,
                },
            ],
        }
        path = directory / "manifest.json"
        path.write_text(json.dumps(manifest), encoding="utf-8")
        return path

    def test_manifest_gates_and_metrics(self) -> None:
        with tempfile.TemporaryDirectory() as directory_name:
            directory = Path(directory_name)
            path = self.make_manifest(directory)
            dataset_id, records = load_evaluation_manifest(path, split="test")
            result = evaluate(AmplitudeClassifier(), records, dataset_id=dataset_id)
        door = result["per_class"]["door_knock"]
        self.assertEqual(door["true_positive"], 1)
        self.assertEqual(door["false_positive"], 0)
        self.assertEqual(door["recall"], 1.0)
        self.assertEqual(result["missed_event_rate"], 0.0)
        self.assertEqual(result["inference_latency_ms"]["p95"], 2.5)

    def test_missing_consent_is_rejected_before_inference(self) -> None:
        with tempfile.TemporaryDirectory() as directory_name:
            path = self.make_manifest(Path(directory_name), consent=False)
            with self.assertRaises(DatasetValidationError):
                load_evaluation_manifest(path, split="test")

    def test_checksum_mismatch_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as directory_name:
            directory = Path(directory_name)
            path = self.make_manifest(directory)
            manifest = json.loads(path.read_text(encoding="utf-8"))
            manifest["records"][0]["sha256"] = "0" * 64
            path.write_text(json.dumps(manifest), encoding="utf-8")
            with self.assertRaises(DatasetValidationError):
                load_evaluation_manifest(path, split="test")

    def test_short_audio_is_padded_without_mutation(self) -> None:
        source = (1, 2, 3)
        windows = list(audio_windows(source))
        self.assertEqual(len(windows), 1)
        self.assertEqual(len(windows[0]), 16_000)
        self.assertEqual(windows[0][:3], source)


if __name__ == "__main__":
    unittest.main()

